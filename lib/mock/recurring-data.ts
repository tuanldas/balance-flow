export function getRecurringSummary(): RecurringSummary {
    const paidItems = mockRecurrings.filter((r) => r.isPaid);
    const unpaidItems = mockRecurrings.filter((r) => !r.isPaid);

    const paidSoFar = paidItems.reduce((sum, r) => sum + r.amount, 0);
    const leftToPay = unpaidItems.reduce((sum, r) => sum + r.amount, 0);

    return {
        leftToPay,
        paidSoFar,
        totalAmount: paidSoFar + leftToPay,
        currency: 'USD',
    };
}
